// Writes the SQL that appends the link to its documentation page to the description of every plugin pack
// documented in packs.json (portal DB ivertix_portal, table plugin_pack, matched by unique_id).
// The docs host and the release are variables at the top of the SQL, so the same file runs on the dev and
// the productive portal. Packs whose description already has the link are skipped, so it can be rerun.
//
//   node scripts/pluginpacks/portal-doc-links.mjs > scripts/pluginpacks/portal-doc-links.sql
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const { packs } = JSON.parse(fs.readFileSync(path.join(dir, "packs.json"), "utf8"));

const sql = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
const rows = Object.entries(packs)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([uid, p]) => `    (${uid}, ${sql("/monitoringplugins/" + p.page.replace(/\.mdx?$/, ""))})`);
const names = Object.entries(packs)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([uid, p]) => `--   ${uid}: ${p.name}`);

process.stdout.write(`-- Appends the link to the documentation page to the description of the documented plugin packs.
-- Generated by scripts/pluginpacks/portal-doc-links.mjs from packs.json, do not edit by hand.
-- Packs whose description already contains the link text are skipped, so the script can be rerun.

-- docs host without trailing slash: dev https://i-vertix-docs-dev.netlify.app, productive https://i-vertix.guide
SET @docs_host = 'https://i-vertix-docs-dev.netlify.app';
-- release to update: the release in preparation (status 'open'); set a version id to update another release
SET @version_id = (SELECT id FROM version WHERE status = 'open' ORDER BY id DESC LIMIT 1);

-- plugin packs (unique_id):
${names.join("\n")}
DROP TEMPORARY TABLE IF EXISTS tmp_plugin_pack_doc;
CREATE TEMPORARY TABLE tmp_plugin_pack_doc (
    unique_id INT NOT NULL PRIMARY KEY,
    doc_path VARCHAR(255) NOT NULL
);
INSERT INTO tmp_plugin_pack_doc (unique_id, doc_path) VALUES
${rows.join(",\n")};

-- preview: packs that get the link
SELECT pp.id, pp.unique_id, pp.name, CONCAT(@docs_host, d.doc_path) AS doc_url
FROM plugin_pack pp
JOIN tmp_plugin_pack_doc d ON d.unique_id = pp.unique_id
WHERE pp.version_id = @version_id
  AND pp.description NOT LIKE '%>IT Monitoring Plugin Packs</a>%'
ORDER BY pp.name;

UPDATE plugin_pack pp
JOIN tmp_plugin_pack_doc d ON d.unique_id = pp.unique_id
SET pp.description = CONCAT(
    REGEXP_REPLACE(pp.description, '[[:space:]]+$', ''),
    '\\n\\nFor more information, see the <a href="', @docs_host, d.doc_path,
    '" target="_blank" rel="noopener noreferrer">IT Monitoring Plugin Packs</a>.'
)
WHERE pp.version_id = @version_id
  AND pp.description NOT LIKE '%>IT Monitoring Plugin Packs</a>%';

DROP TEMPORARY TABLE tmp_plugin_pack_doc;
`);
